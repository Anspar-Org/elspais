"""Pytest JSON parser for test results.

This parser extracts test results from pytest JSON format files
(generated by pytest-json-report or similar plugins).
Matches a result to its test by recorded identity.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import TYPE_CHECKING, Any

from elspais.graph.parsers.results.diagnostics import DiagnosticRecorder
from elspais.utilities.test_identity import build_test_id_from_nodeid, build_test_id_from_result

if TYPE_CHECKING:
    from elspais.utilities.patterns import IdResolver


class PytestJSONParser(DiagnosticRecorder):
    """Parser for Pytest JSON test result files.

    Parses JSON output from pytest-json-report or similar pytest plugins.

    Matches a result to its test by recorded identity, not by reading
    requirement references out of a reported test name.
    """

    def __init__(
        self,
        resolver: IdResolver | None = None,
        base_path: Path | None = None,
    ) -> None:
        """Initialize PytestJSONParser with optional configuration.

        Args:
            resolver: IdResolver for ID structure. If None, uses defaults.
            base_path: Base path for resolving file-specific configs.
        """
        self._resolver = resolver
        self._base_path = base_path or Path(".")

    def _get_resolver(self) -> IdResolver:
        """Get IdResolver from instance or create default.

        Returns:
            IdResolver to use for parsing.
        """
        if self._resolver is not None:
            return self._resolver

        # The shipped defaults, not a configuration written out here: a
        # hand-built one describes a repository that may not exist, and
        # this one described a shape the schema does not admit at all.
        from elspais.config import config_defaults
        from elspais.utilities.patterns import build_resolver

        return build_resolver(config_defaults())

    # Implements: REQ-d00285-G
    def parse(self, content: str, source_path: str) -> list[dict[str, Any]]:
        """Parse Pytest JSON content and return test result dicts.

        Args:
            content: JSON file content.
            source_path: Path to the source file.

        Returns:
            List of test result dictionaries with keys:
            - ordinal: Position of the record in this report
            - name: Test name
            - classname: Test class/module name
            - status: passed, failed, skipped, or error
            - duration: Test duration in seconds
            - message: Error/failure message (if any)
        """
        # The position of a record is its place among the records this
        # report yielded, so a test reported once for each environment it
        # ran in keeps one record for each. A test entry this parser
        # declines takes no position.
        results: list[dict[str, Any]] = []
        self._start_diagnostics()

        try:
            data = json.loads(content)
        except json.JSONDecodeError as exc:
            # An unreadable report and a suite that never ran both arrive here
            # as no results. Record which one this was, and the line the
            # decoder stopped at, before returning the empty list.
            self._record_diagnostic(
                source_path,
                f"pytest JSON did not parse: {exc.msg}",
                line=exc.lineno,
            )
            return results

        # Implements: REQ-d00285-G, REQ-d00294-E
        # Records whose outcome this reporter cannot read, as (name, outcome).
        # Such a record is neither a pass nor a failure; reading it as either
        # is a guess, and a guess towards passing hides a failure. It is
        # declined and reported instead.
        self._unread: list[tuple[str, Any]] = []

        # Handle pytest-json-report format
        if isinstance(data, dict) and "tests" in data:
            for test in data["tests"]:
                result = self._parse_pytest_json_report_test(test, source_path)
                if result:
                    # Implements: REQ-d00294-A
                    result["ordinal"] = len(results) + 1
                    results.append(result)
        # Handle simpler format with just a list of tests
        elif isinstance(data, list):
            for test in data:
                result = self._parse_simple_test(test, source_path)
                if result:
                    # Implements: REQ-d00294-A
                    result["ordinal"] = len(results) + 1
                    results.append(result)
        else:
            # Implements: REQ-d00285-G
            # Valid JSON in a shape this reporter does not read. The document
            # was there and was declined; that is not the same as a run that
            # reported nothing.
            self._record_diagnostic(
                source_path,
                "pytest JSON parsed but holds neither a 'tests' mapping nor a list of tests",
            )

        for name, outcome in self._unread:
            described = "no outcome" if outcome is None else f"outcome {outcome!r}"
            self._record_diagnostic(
                source_path,
                f"pytest JSON record {name!r} carries {described}, which this "
                f"reporter does not read as a pass, a failure or a skip",
                partial=bool(results),
            )
        return results

    # Implements: REQ-d00285-G, REQ-d00294-E
    def _read_outcome(self, raw: Any, table: dict[str, str | None], name: str) -> str | None:
        """The status *raw* reads as, or None where the record is declined.

        A value is compared without regard to case or surrounding space. A
        value the table maps to None is an attempt rather than a verdict (a
        rerun that a later record of the same test settles) and is declined
        without a report; a value the table does not hold, or a missing one,
        is declined and reported.
        """
        key = str(raw).strip().lower() if raw is not None else None
        if key is not None and key in table:
            return table[key]
        self.__dict__.setdefault("_unread", []).append((name, raw))
        return None

    def _parse_pytest_json_report_test(
        self, test: dict[str, Any], source_path: str
    ) -> dict[str, Any] | None:
        """Parse a test from pytest-json-report format.

        Args:
            test: Test dict from pytest-json-report.
            source_path: Path to the source file.

        Returns:
            Parsed test result dict or None.
        """
        nodeid = test.get("nodeid", "")

        # Parse nodeid to get module and test name
        # Format: path/to/test.py::TestClass::test_method
        # or: path/to/test.py::test_function
        parts = nodeid.split("::")
        if len(parts) >= 2:
            classname = parts[0]
            name = "::".join(parts[1:])
        else:
            classname = ""
            name = nodeid

        # Map outcome to status
        status_map: dict[str, str | None] = {
            "passed": "passed",
            "failed": "failed",
            "skipped": "skipped",
            "error": "error",
            "xfailed": "skipped",  # Expected failure
            "xpassed": "passed",  # Unexpected pass
            "rerun": None,  # an attempt; the test's own record carries its verdict
        }
        status = self._read_outcome(test.get("outcome"), status_map, nodeid)
        if status is None:
            return None

        # Get duration
        duration = 0.0
        if "duration" in test:
            duration = float(test["duration"])
        elif "call" in test and "duration" in test["call"]:
            duration = float(test["call"]["duration"])

        # Get message from call or setup/teardown
        message = None
        for phase in ["call", "setup", "teardown"]:
            if phase in test:
                phase_data = test[phase]
                if isinstance(phase_data, dict):
                    if "longrepr" in phase_data:
                        message = str(phase_data["longrepr"])[:200]
                        break
                    elif "message" in phase_data:
                        message = str(phase_data["message"])[:200]
                        break

        # Generate canonical TEST node ID from nodeid (already has file path)
        test_id = build_test_id_from_nodeid(nodeid)

        return {
            "name": name,
            "classname": classname,
            "status": status,
            "duration": duration,
            "message": message,
            "source_path": source_path,
            "test_id": test_id,
            # Results-file provenance: for pytest JSON the results file IS the
            # parsed file; JSON has no meaningful per-record line.
            "result_file": source_path or None,
            "result_line": None,
        }

    def _parse_simple_test(self, test: dict[str, Any], source_path: str) -> dict[str, Any] | None:
        """Parse a test from simple list format.

        Args:
            test: Test dict with name, status, etc.
            source_path: Path to the source file.

        Returns:
            Parsed test result dict or None.
        """
        name = test.get("name", "")
        if not name:
            return None

        classname = test.get("classname", test.get("module", ""))

        # Normalize status
        status_map: dict[str, str | None] = {
            "pass": "passed",
            "passed": "passed",
            "fail": "failed",
            "failed": "failed",
            "failure": "failed",
            "skip": "skipped",
            "skipped": "skipped",
            "error": "error",
            "xfailed": "skipped",
            "xpassed": "passed",
            "rerun": None,
        }
        status = self._read_outcome(test.get("status", test.get("outcome")), status_map, name)
        if status is None:
            return None

        duration = float(test.get("duration", 0))
        message = test.get("message", test.get("longrepr"))
        if message:
            message = str(message)[:200]

        # Generate canonical TEST node ID using test_identity utility
        test_id = build_test_id_from_result(classname, name)

        return {
            "name": name,
            "classname": classname,
            "status": status,
            "duration": duration,
            "message": message,
            "source_path": source_path,
            "test_id": test_id,
            "result_file": source_path or None,
            "result_line": None,
        }

    # Implements: REQ-d00054-A
    def can_parse(self, file_path: Path) -> bool:
        """Check if this parser can handle the given file.

        Args:
            file_path: Path to the file.

        Returns:
            True for JSON files that look like pytest results.
        """
        name = file_path.name.lower()
        return file_path.suffix.lower() == ".json" and (
            "pytest" in name or "test" in name or "result" in name
        )


def create_parser(
    resolver: IdResolver | None = None,
    base_path: Path | None = None,
) -> PytestJSONParser:
    """Factory function to create a PytestJSONParser.

    Args:
        resolver: Optional IdResolver for ID structure.
        base_path: Optional base path for resolving file paths.

    Returns:
        New PytestJSONParser instance.
    """
    return PytestJSONParser(resolver, base_path)
